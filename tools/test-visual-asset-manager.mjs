import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";

const source = fs.readFileSync(new URL("../outputs/editor-visual-asset-manager.js", import.meta.url), "utf8");
const context = { window: {} };
vm.createContext(context);
vm.runInContext(source, context);

const manager = context.window.EditorVisualAssetManager;
assert.ok(manager);
assert.ok(Object.keys(manager.ICONS).length >= 20);
assert.ok(Object.keys(manager.DECORATION_STYLES).length >= 10);
assert.ok(manager.ICONS.heart);
assert.ok(manager.ICONS.recurring);
assert.ok(manager.ICONS["clipboard-edit"]);
assert.ok(manager.ICONS.award);
assert.ok(Array.isArray(manager.STICKER_KEYS));
assert.ok(manager.STICKER_KEYS.length >= 20);
assert.ok(manager.STICKER_CATEGORIES);
assert.equal(manager.STICKER_CATEGORIES.nature.label, "자연");
assert.equal(manager.STICKER_CATEGORIES.nature.keys.length, 40);
assert.equal(new Set(manager.STICKER_CATEGORIES.nature.keys).size, 40);
assert.ok(manager.STICKER_CATEGORIES.nature.keys.every((key) => manager.ICONS[key]?.stickerCategory === "nature"));
assert.equal(manager.STICKER_CATEGORIES.earth.label, "지구");
assert.equal(manager.STICKER_CATEGORIES.earth.keys.length, 40);
assert.equal(new Set(manager.STICKER_CATEGORIES.earth.keys).size, 40);
assert.ok(manager.STICKER_CATEGORIES.earth.keys.every((key) => manager.ICONS[key]?.stickerCategory === "earth"));
assert.equal(manager.STICKER_CATEGORIES.daily.label, "일상");
assert.equal(manager.STICKER_CATEGORIES.daily.keys.length, 40);
assert.equal(new Set(manager.STICKER_CATEGORIES.daily.keys).size, 40);
assert.ok(manager.STICKER_CATEGORIES.daily.keys.every((key) => manager.ICONS[key]?.stickerCategory === "daily"));
assert.ok(manager.STICKER_CATEGORIES.basic.keys.length >= 20);
assert.ok(manager.ICONS["sticker-heart-smile"]);
assert.ok(manager.ICONS["sticker-earth-smile"]);
assert.ok(manager.ICONS["sticker-nature-friend-leaf"]);
assert.ok(manager.ICONS["sticker-nature-outline-cactus"]);
assert.ok(manager.ICONS["sticker-earth-outline-globe"]);
assert.ok(manager.ICONS["sticker-earth-friend-heart-hands"]);
assert.ok(manager.ICONS["sticker-daily-color-heart-wave"]);
assert.ok(manager.ICONS["sticker-daily-motion-dotted-loop"]);
assert.match(manager.renderIcon("sticker-nature-friend-leaf"), /nature-friend-leaf\.png/);
assert.match(manager.renderIcon("sticker-earth-friend-heart-hands"), /earth-friend-heart-hands\.png/);
assert.match(manager.renderIcon("sticker-daily-motion-dotted-loop"), /daily-motion-dotted-loop\.png/);
assert.equal(manager.ICONS["sticker-heart-smile"].category, "sticker");
assert.equal(manager.normalizeDecoration({ icon: "sprout", style: "ring" }).icon, "sprout");
assert.equal(manager.normalizeDecoration({ icon: null, style: "solid-circle" }).icon, null);
assert.equal(manager.normalizeDecoration({ icon: "missing", style: "missing" }).icon, "heart");
assert.equal(manager.normalizeDecoration({ icon: "missing", style: "missing" }).style, "plain");
assert.match(manager.renderIcon("heart"), /<svg/);

console.log("visual asset manager tests OK");
